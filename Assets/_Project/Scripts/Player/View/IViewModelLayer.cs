namespace CrateExpectations.Player.View
{
    /// <summary>
    /// Слой поверх базового кадрирования вьюмодели: взмах, покачивание от ходьбы, отдача,
    /// увод камерой - всё, что двигает руки относительно подобранной стойки.
    /// <para>
    /// Слой знает только про себя: он не читает соседей, не складывается ни с кем и не
    /// трогает <see cref="UnityEngine.Transform"/>. Он отвечает на один вопрос - "какую
    /// добавку я даю в этом кадре", - а складывает добавки <see cref="ViewModelRig"/>.
    /// Поэтому новый слой добавляется компонентом на объект вьюмодели и не требует правок
    /// ни в риге, ни в соседних слоях.
    /// </para>
    /// </summary>
    public interface IViewModelLayer
    {
        /// <summary>
        /// Добавка этого слоя в текущем кадре. Слой, которому сейчас нечего сказать,
        /// возвращает <see cref="ViewModelOffset.None"/>, а не выключается: включение
        /// и выключение компонента меняло бы порядок слоёв
        /// </summary>
        ViewModelOffset Evaluate();
    }
}
