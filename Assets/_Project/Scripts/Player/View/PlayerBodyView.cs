using CrateExpectations.Core.Hands;
using UnityEngine;
using UnityEngine.Rendering;

namespace CrateExpectations.Player.View
{
    /// <summary>
    /// Физическое тело игрока. Висит на корне модели, который лежит дочерним объектом под
    /// физическим корнем игрока - оттуда тело бесплатно получает позицию и yaw, причём yaw
    /// уже интерполированный, тот же самый, по которому строится камера.
    /// <para>
    /// Тело ВИДНО из собственных глаз: опустив взгляд, игрок видит свои руки, ноги и
    /// ботинки. Раньше вся модель стояла в <see cref="ShadowCastingMode.ShadowsOnly"/>
    /// и под ногами не было ничего, кроме пола, - камера висела в воздухе.
    /// </para>
    /// <para>
    /// Скрытой остаётся одна голова: камера сидит в черепе, и показывать его значит
    /// показывать изнанку. Торс в кадре есть, и держится он на том, что ГЛАЗ ЕДЕТ
    /// ВМЕСТЕ С ГРУДЬЮ (<see cref="_chestBone"/>). Неподвижная камера торс показать
    /// не может в принципе: замер по вершинам говорит, что в позе бега грудь уходит
    /// вперёд от оси тела на 0.403 м, то есть наезжает на объектив каждый шаг.
    /// Привязка к груди убирает это целиком - грудь стоит относительно глаза неподвижно,
    /// как и в жизни.
    /// </para>
    /// <para>
    /// Плата за это - качка: камера повторяет подъёмы и наклоны корпуса из клипа.
    /// Поэтому привязка не жёсткая, а с двумя ручками в
    /// <see cref="FirstPersonCameraDefinition"/>: доля повторяемой качки (ноль возвращает
    /// прежнюю неподвижную камеру целиком) и сглаживание, срезающее самую высокую частоту.
    /// Сглаживается ОТКЛОНЕНИЕ кости от покоя, а не мировая позиция глаза: сглаженная
    /// мировая позиция отставала бы от идущего игрока и тащилась за ним на верёвке.
    /// </para>
    /// <para>
    /// Вся посадка глаза - высота, вынос и обе ручки качки - живёт в ассете, а не в полях
    /// этого компонента: её подбирают на глаз и в play mode, а правка сцены выход из него
    /// не переживает.
    /// </para>
    /// <para>
    /// Скрытое именно гасится в <c>ShadowsOnly</c>, а не выключается: <c>enabled = false</c>
    /// унёс бы вместе с головой и её тень, и силуэт игрока на земле стал бы безголовым.
    /// </para>
    /// <para>
    /// С руками сложнее, и правило у них общее с вьюмоделью. Рук у игрока в кадре может быть
    /// только одна пара: либо свои, телесные, - тогда он видит, как они болтаются при беге, -
    /// либо вьюмодельные, поднятые к объективу с саблей, грузом или листком. Обе пары
    /// одновременно - это четыре руки. Поэтому телесные руки видны ровно тогда, когда руки
    /// СВОБОДНЫ, то есть ровно тогда, когда <see cref="ViewModelBody"/> свои прячет.
    /// Занятость спрашивается у общей модели <see cref="HandsState"/>, а не заводится
    /// вторым списком условий: местная копия разъехалась бы с ней в первый же раз,
    /// когда груз выпадет из рук сам.
    /// </para>
    /// <para>
    /// К кости ГОЛОВЫ камера не привязана по-прежнему, и это не то же самое, что грудь:
    /// голову боевые клипы мотают отдельно от корпуса и с куда большей амплитудой.
    /// Поворот кости груди тоже не наследуется - берётся только её СМЕЩЕНИЕ, а
    /// направление выноса глаза считается от yaw тела. Иначе скрутка корпуса в беге
    /// кренила бы горизонт.
    /// </para>
    /// <para>
    /// Наклон вверх-вниз живёт на пивоте камеры и в тело не уходит вообще - тело только
    /// поворачивается вслед за взглядом по горизонтали.
    /// </para>
    /// </summary>
    public sealed class PlayerBodyView : MonoBehaviour
    {
        [Tooltip("Пивот, на котором PlayerController крутит наклон камеры. " +
                 "Этот компонент задаёт ему только высоту, поворот не трогает")]
        [SerializeField] private Transform _cameraPivot;

        [Tooltip("Посадка камеры: высота глаза, вынос вперёд и повторение качки груди. " +
                 "Все числа живут в ассете, а не здесь, ровно потому, что их подбирают " +
                 "на глаз и в play mode: правка ассета выход из него переживает, " +
                 "правка компонента в сцене - нет")]
        [SerializeField] private FirstPersonCameraDefinition _camera;

        [Tooltip("Что не показываем никогда: голова - ровно то, внутри чего стоит камера " +
                 "(замер: ближайшая вершина в 0.015 м от глаза). Тень при этом остаётся - " +
                 "силуэт на земле обязан быть с головой")]
        [SerializeField] private Renderer[] _hiddenRenderers;

        [Header("Глаз на кости груди")]
        [Tooltip("Кость груди (верхняя кость позвоночника). Глаз едет вместе с ней, " +
                 "и только поэтому торс можно показывать: собственная грудь перестаёт " +
                 "наезжать на объектив при наклоне корпуса. Пусто - камера остаётся " +
                 "неподвижной, как была, и торс придётся снова прятать")]
        [SerializeField] private Transform _chestBone;

        [Tooltip("Руки тела. Видны, только когда руки свободны: занятые руки показывает " +
                 "вьюмодель, и две пары сразу - это четыре руки в кадре")]
        [SerializeField] private Renderer _armsRenderer;

        private HandsState _hands;

        // Совпадает с тем, что сделал Awake: руки показаны, как у свободных
        private bool _armsVisible = true;

        private readonly EyeBobFilter _bob = new EyeBobFilter();

        /// <summary>
        /// Где кость груди стоит в покое, в осях тела. Снимается с первого кадра, а не
        /// задаётся числом в инспекторе: покой - это то, где кость СТОИТ, и второе число
        /// про то же самое разъехалось бы с моделью в первый же раз, когда её заменят
        /// </summary>
        private Vector3 _chestRest;

        private bool _chestRestTaken;

        /// <summary>
        /// Отдаёт телу модель занятости рук - ссылкой из <c>GameLifetimeScope</c>, а не
        /// поиском по иерархии, по тем же причинам, что и у <see cref="ViewModelBody"/>:
        /// поиск отдаёт первое совпадение в порядке объектов сцены и молча разъезжается,
        /// стоит их переставить. Забытая ссылка оставит <c>_hands</c> пустым, и руки
        /// просто останутся видимыми всегда - отказ заметен сразу
        /// </summary>
        public void BindHands(HandsState hands) => _hands = hands;

        private void Awake()
        {
            if (_cameraPivot == null)
            {
                Debug.LogError($"Телу игрока '{name}' не назначен пивот камеры - высоту глаз задавать нечему.", this);
                enabled = false;
                return;
            }

            // Ассет посадки - не мелочь, которую можно подставить по умолчанию: без него
            // глаз оказался бы в нуле, то есть в подошвах, и понять это по чёрному
            // экрану было бы нельзя
            if (_camera == null)
            {
                Debug.LogError($"Телу игрока '{name}' не назначен ассет посадки камеры " +
                               "(FirstPersonCameraDefinition) - ставить глаз некуда.", this);
                enabled = false;
                return;
            }

            ShowBody();
        }

        /// <summary>
        /// Тело показываем целиком, кроме перечисленного. Проход по ВСЕМ рендерерам, а не
        /// по списку видимых: модель собрана из пяти кусков, и любой шестой, добавленный
        /// в неё потом, обязан появиться в кадре сам, а не после правки этого файла
        /// </summary>
        private void ShowBody()
        {
            int shown = 0;

            foreach (Renderer renderer in GetComponentsInChildren<Renderer>(true))
            {
                renderer.shadowCastingMode = ShadowCastingMode.On;
                shown++;
            }

            if (shown == 0)
            {
                Debug.LogWarning($"У тела игрока '{name}' нет ни одного рендерера - " +
                                 "ни тела в кадре, ни тени на земле не будет.", this);
                return;
            }

            if (_hiddenRenderers == null || _hiddenRenderers.Length == 0)
            {
                Debug.LogWarning($"Телу игрока '{name}' не назначено ни одного скрытого куска - " +
                                 "камера стоит внутри головы, и в кадре будет её изнанка.", this);
            }
            else
            {
                foreach (Renderer renderer in _hiddenRenderers)
                    if (renderer != null)
                        renderer.shadowCastingMode = ShadowCastingMode.ShadowsOnly;
            }

            if (_armsRenderer == null)
                Debug.LogWarning($"Телу игрока '{name}' не назначены руки - они останутся " +
                                 "в кадре вместе с руками вьюмодели, то есть вчетвером.", this);
        }

        /// <summary>
        /// Занятость не «меняется», а вычисляется из трёх источников - события у неё нет,
        /// и опрос здесь не лень, а единственный честный способ её узнать. Рендерер при этом
        /// трогаем только на смене
        /// </summary>
        private void Update()
        {
            if (_hands == null || _armsRenderer == null)
                return;

            bool visible = _hands.Occupancy == HandsOccupancy.Free;

            if (visible == _armsVisible)
                return;

            _armsVisible = visible;

            // Спрятанные руки продолжают отбрасывать тень: силуэт на земле не обязан
            // терять руки от того, что игрок взял ящик
            _armsRenderer.shadowCastingMode =
                visible ? ShadowCastingMode.On : ShadowCastingMode.ShadowsOnly;
        }

        /// <summary>
        /// Позу глаза применяем покадрово, а не один раз в <c>Awake</c>: числа подбирают
        /// руками, в том числе на ходу в play mode, и результат должен быть виден сразу.
        /// <para>
        /// Именно в <c>LateUpdate</c>, и это обязательно: кость груди двигает аниматор,
        /// и глаз, поставленный до него, отставал бы от неё ровно на кадр - то есть
        /// дрожал бы с частотой кадров вместо того, чтобы стоять в груди неподвижно
        /// </para>
        /// </summary>
        private void LateUpdate()
        {
            Vector3 seated =
                transform.position + transform.up * _camera.Height + transform.forward * _camera.Forward;

            _cameraPivot.position = seated + transform.rotation * ChestDeviation();
        }

        /// <summary>
        /// Куда уехала грудь от своего покоя, в осях тела и уже сглаженно. Ноль, если
        /// кость не назначена: тогда камера стоит там же, где стояла до всей этой затеи
        /// </summary>
        private Vector3 ChestDeviation()
        {
            if (_chestBone == null)
                return Vector3.zero;

            Vector3 chestLocal = transform.InverseTransformPoint(_chestBone.position);

            // Покой снимаем с первого же кадра - до него отклонения нет по определению,
            // и вычитать было бы не из чего
            if (!_chestRestTaken)
            {
                _chestRest = chestLocal;
                _chestRestTaken = true;
            }

            return _bob.Tick(
                chestLocal - _chestRest, _camera.ChestFollow, _camera.ChestSmoothTime, Time.deltaTime);
        }
    }
}
