using UnityEngine;

namespace CrateExpectations.Player.View
{
    /// <summary>
    /// Посадка камеры от первого лица: где стоит глаз и насколько он повторяет качку тела.
    /// Все числа - здесь, чтобы их можно было подбирать в play mode и не потерять на выходе
    /// из него: правка ассета переживает выход, правка компонента в сцене - нет.
    /// <para>
    /// Числа связаны между собой, и связь неочевидная. Тело игрока видно из собственных
    /// глаз, а модель одета: воротник поднимается до высоты 1.597 и опоясывает камеру
    /// на уровне груди от -0.105 до +0.094 по Z. Глаз, оказавшийся внутри этого кольца,
    /// смотрит на изнанку модели, и НИКАКОЙ предел наклона этого не лечит - изнанка
    /// видна на всех углах. Вытаскивают глаз из одежды два числа сразу: высота и вынос.
    /// </para>
    /// <para>
    /// Ещё одна ловушка: <see cref="CameraForward"/> - это не то, что получится в итоге.
    /// К нему складывается качка груди, и в покое она тянет глаз НАЗАД примерно на 0.038.
    /// Вынос 0.10 на деле даёт 0.062. Проверять посадку надо по фактическому положению
    /// камеры, а не по числу в этом поле.
    /// </para>
    /// </summary>
    [CreateAssetMenu(
        fileName = "FirstPersonCameraDefinition",
        menuName = "CrateExpectations/Player/First Person Camera")]
    public sealed class FirstPersonCameraDefinition : ScriptableObject
    {
        [Header("Где стоит глаз")]
        [Tooltip("Высота глаза над подошвами, м. Чем ниже - тем меньше собственных плеч " +
                 "нависает над кадром и тем больше кадр начинается «от груди». Ниже 1.55 " +
                 "лезть незачем: кромка воротника поднимается до 1.597, и глаз уходит " +
                 "внутрь кольца одежды - вытаскивать придётся выносом")]
        [Min(0f)] [field: SerializeField] public float Height { get; private set; } = 1.6f;

        [Tooltip("Вынос глаза вперёд от оси тела, м, в осях ТЕЛА. Главная ручка кадра, " +
                 "и работает она в обе стороны. Мало (меньше ~0.25) - глаз оказывается " +
                 "ВНУТРИ воротника, и вниз видно изнанку модели на любом наклоне. " +
                 "Много (больше ~0.30) - тело уходит из кадра вовсе, и смотреть вниз " +
                 "снова не на что. На 0.28 ближайшая ткань стоит в 0.131 м, дальше " +
                 "ближней плоскости камеры. К этому числу прибавляется качка груди: " +
                 "в покое она тянет глаз назад примерно на 0.038")]
        [Min(0f)] [field: SerializeField] public float Forward { get; private set; } = 0.28f;

        [Header("Качка вслед за грудью")]
        [Tooltip("Какую долю качки груди повторяет камера. 1 - глаз жёстко сидит в груди " +
                 "и торс держится в кадре неподвижно; 0 - неподвижная камера, но тогда " +
                 "собственная грудь начнёт наезжать на объектив при наклоне корпуса " +
                 "(в позе бега она уходит вперёд на 0.403 м). Это ручка обмена: " +
                 "чем больше, тем честнее тело и тем сильнее качает на бегу")]
        [Range(0f, 1f)] [field: SerializeField] public float ChestFollow { get; private set; } = 1f;

        [Tooltip("Сглаживание качки, с. Срезает самую высокую частоту - удары стопы, - " +
                 "не трогая общий подъём корпуса. Замер качки за цикл бега: 4.4 см " +
                 "вверх-вниз, 4.4 вперёд-назад, 2.3 вбок. Держать маленьким: большое " +
                 "превратит качку в плавание, а глаз начнёт отставать от собственной груди")]
        [Min(0f)] [field: SerializeField] public float ChestSmoothTime { get; private set; } = 0.05f;
    }
}
