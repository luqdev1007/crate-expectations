using CrateExpectations.Combat;
using CrateExpectations.Core.Input;
using UnityEngine;
using VContainer;

namespace CrateExpectations.Player
{
    /// <summary>
    /// Смерть игрока — <b>заглушка</b>, и названа так честно: она делает ровно одно —
    /// отбирает ввод. Ни экрана, ни перезапуска смены, ни падения камеры здесь нет,
    /// и появиться они должны не тут.
    /// <para>
    /// Почему заглушка вообще нужна, если ничего не показывает. Без неё смерть игрока
    /// не наблюдаема: здоровье честно уходит в ноль, <c>CharacterDied</c> честно летит
    /// в шину — и игрок продолжает бегать и рубить как ни в чём не бывало. Отобранный
    /// ввод превращает «где-то в модели что-то посчиталось» в событие, которое видно
    /// из-за клавиатуры, и делает это одной строкой, ничего не предрешая насчёт того,
    /// как смерть будет выглядеть потом.
    /// </para>
    /// <para>
    /// Тело игрока при этом НЕ трогается: ни регдола, ни выключения контроллера.
    /// Регдол от первого лица — это отдельная работа (камера должна уехать с костью
    /// груди, а вьюмодель — исчезнуть), и делать её наполовину хуже, чем не делать:
    /// половина читалась бы как поломка. Игрок остаётся стоять там, где умер,
    /// и больше ничего не может — этого достаточно, чтобы смерть была видна
    /// </para>
    /// </summary>
    [RequireComponent(typeof(HealthComponent))]
    public sealed class PlayerDeath : MonoBehaviour
    {
        private HealthComponent _health;
        private IInputReader _input;

        [Inject]
        public void Construct(IInputReader input) => _input = input;

        private void Awake() => _health = GetComponent<HealthComponent>();

        private void OnEnable() => _health.Died += Die;

        private void OnDisable() => _health.Died -= Die;

        /// <param name="lastHit">
        /// Добивший удар. Здесь не используется: падать нечему, толкать некого.
        /// Параметр остаётся частью подписи события, а не выбрасывается из неё, -
        /// заглушку заменят, и первое, что понадобится настоящей смерти, это как раз
        /// «откуда прилетело»
        /// </param>
        private void Die(HitInfo lastHit)
        {
            // Ввод, а не компоненты игрока. Гасить PlayerController, Interactor,
            // Carrier и бой поимённо значило бы завести здесь список того, из чего
            // состоит игрок, и обязать каждого, кто добавит ему новую способность,
            // вспомнить про этот файл. Ввод - одна точка на всех
            _input?.SetEnabled(false);

            Debug.Log($"[Смерть] '{name}' убит. Ввод отключён — это заглушка, " +
                      "экран смерти и перезапуск смены будут отдельной задачей.", this);

            enabled = false;
        }
    }
}
