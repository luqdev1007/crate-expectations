namespace CrateExpectations.Core.Hands
{
    /// <summary>
    /// Кто отвечает на вопросы про оружие в руке. Два вопроса, а не один, потому что
    /// они разные: «сабля достана» - это про занятость рук вообще, «занят» - про то,
    /// можно ли прямо сейчас начать что-то другое.
    /// </summary>
    public interface IWeaponStateSource
    {
        /// <summary>
        /// Оружие не за поясом. Включая доставание и убирание: обе фазы заняты руками
        /// ровно так же, как готовая стойка
        /// </summary>
        bool IsWeaponDrawn { get; }

        /// <summary>
        /// Идёт действие, из которого нельзя мгновенно перейти к другому: удар вместе
        /// с замахом и доводкой, набор заряда, любая фаза блока, доставание и убирание.
        /// Ready и Sheathed сюда не входят - из них игрок свободен делать что угодно
        /// </summary>
        bool IsBusy { get; }
    }
}
