namespace CrateExpectations.Core.Hands
{
    /// <summary>
    /// Кто отвечает на вопрос «в руках сейчас груз?». Интерфейс живёт в Core, а реализует
    /// его переноска: <see cref="HandsState"/> обязан читать состояние у ЕГО ВЛАДЕЛЬЦА,
    /// а не заводить собственную копию, иначе две правды разъедутся в первый же кадр,
    /// когда груз выпадет из рук сам (например, застрял за геометрией).
    /// </summary>
    public interface ICarryStateSource
    {
        /// <summary>Держит ли игрок что-нибудь в руках прямо сейчас</summary>
        bool IsCarrying { get; }
    }
}
