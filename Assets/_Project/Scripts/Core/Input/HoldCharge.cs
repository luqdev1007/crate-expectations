namespace CrateExpectations.Core.Input
{
    /// <summary>
    /// Удержание кнопки, переведённое в заряд. Один механизм на весь проект: и удар,
    /// который выбирает приём по длительности удержания, и бросок груза, который копит
    /// замах, - это один и тот же счёт времени между нажатием и отпусканием.
    /// Два своих таймера с двумя своими порогами разъехались бы в первый же раз,
    /// когда порог понадобилось бы подкрутить.
    /// <para>
    /// Два числа, и они разные. <b>Порог активации</b> - мёртвая зона: удержание короче
    /// него не считается удержанием вообще (короткий тап по кнопке броска не должен
    /// ронять груз слабым тычком). <b>Длительность</b> - сколько копить ПОСЛЕ порога
    /// до полного заряда. У боя мёртвой зоны нет: любое нажатие - это уже удар,
    /// вопрос только какой.
    /// </para>
    /// <para>
    /// Класс ничего не решает за владельца. <see cref="Tick"/> лишь СООБЩАЕТ - ровно
    /// один раз, - что заряд дошёл до полного; гасить его при этом или дать кнопке
    /// висеть в полном заряде, решает тот, кто держит экземпляр. Бой на этот сигнал
    /// бьёт сам, не дожидаясь отпускания; бросок ждёт отпускания, стоя на единице.
    /// </para>
    /// <para>
    /// Обычный C#-класс без единой ссылки на UnityEngine: время приходит аргументом
    /// <see cref="Tick"/>, и порог проверяется тестом, а не секундомером в play mode.
    /// </para>
    /// </summary>
    public sealed class HoldCharge
    {
        private float _activation;
        private float _duration;

        // Полный заряд - это команда, а не состояние, и повторять её нельзя: без флага
        // владелец получал бы «готово» каждый кадр, пока кнопка зажата
        private bool _fullReported;

        /// <summary>Кнопка зажата и время идёт. Включая мёртвую зону до порога активации</summary>
        public bool IsHolding { get; private set; }

        /// <summary>Сколько удержание уже длится, с. Считается от нажатия, вместе с мёртвой зоной</summary>
        public float Held { get; private set; }

        /// <summary>
        /// Заряд реально копится: кнопка зажата И мёртвая зона пройдена. Это и есть
        /// «замах пошёл» для всех, кто его показывает, - от аниматора до точки удержания груза
        /// </summary>
        public bool IsCharging => IsHolding && Held >= _activation;

        /// <summary>
        /// Насколько заряд полон, 0..1. Ноль внутри мёртвой зоны, единица по достижении
        /// полного - и дальше единица, сколько бы кнопку ни держали.
        /// <para>
        /// Переживает <see cref="Release"/>: отпускание останавливает время, но накопленное
        /// остаётся читаемым, иначе владельцу пришлось бы снимать заряд ДО отпускания
        /// и помнить об этом порядке. Забывает накопленное только <see cref="Cancel"/>
        /// </para>
        /// </summary>
        public float ChargeT
        {
            get
            {
                if (Held < _activation)
                    return 0f;

                // Копить нечего - значит, уже полный. Проверка идёт РАНЬШЕ деления,
                // и не только ради него: так ведёт себя удар без заряда, и «полный
                // с первого кадра» - это про него правда
                if (_duration <= 0f)
                    return 1f;

                float past = Held - _activation;

                return past >= _duration ? 1f : past / _duration;
            }
        }

        /// <summary>
        /// Кнопку нажали. Оба числа приходят снаружи, потому что они свойство ДЕЙСТВИЯ:
        /// у удара вперёд свой порог, у броска свой, и знать об этом должна раскладка
        /// или ассет, а не счётчик времени
        /// </summary>
        /// <param name="chargeDuration">Сколько копить после порога до полного заряда, с</param>
        /// <param name="activationThreshold">
        /// Мёртвая зона: короче неё удержание не считается начатым. Ноль - зоны нет
        /// </param>
        public void Begin(float chargeDuration, float activationThreshold)
        {
            _duration = chargeDuration > 0f ? chargeDuration : 0f;
            _activation = activationThreshold > 0f ? activationThreshold : 0f;

            Held = 0f;
            IsHolding = true;
            _fullReported = false;
        }

        /// <summary>
        /// Копит удержание. Возвращает <c>true</c> ровно один раз - в тот кадр, когда заряд
        /// стал полным. Сам заряд при этом НЕ гасится: что значит «полный», решает владелец
        /// </summary>
        public bool Tick(float deltaTime)
        {
            if (!IsHolding)
                return false;

            Held += deltaTime;

            if (_fullReported || Held < _activation + _duration)
                return false;

            _fullReported = true;

            return true;
        }

        /// <summary>
        /// Кнопку отпустили. Останавливает время и отдаёт накопленное удержание, с.
        /// Ноль означает, что держать было нечего, - например, заряд уже сняли.
        /// <see cref="ChargeT"/> и <see cref="Held"/> после этого ещё читаются:
        /// владельцу они нужны ровно в момент отпускания
        /// </summary>
        public float Release()
        {
            if (!IsHolding)
                return 0f;

            IsHolding = false;

            return Held;
        }

        /// <summary>
        /// Забыть удержание целиком, без всяких последствий. Нужно там, где сама
        /// возможность действия пропала: оружие убрали посреди заряда, груз выпал
        /// из рук посреди замаха. Отпущенная потом кнопка не должна выстрелить
        /// </summary>
        public void Cancel()
        {
            IsHolding = false;
            Held = 0f;
            _fullReported = false;
        }
    }
}
