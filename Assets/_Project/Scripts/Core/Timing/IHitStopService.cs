namespace CrateExpectations.Core.Timing
{
    /// <summary>
    /// Короткая заморозка игрового времени на попадании - то, что превращает касание
    /// в удар. Отдельный сервис, а не строчка в боевом коде, ровно по одной причине:
    /// <c>Time.timeScale</c> - глобальная величина, и владеть ей должен ровно один
    /// объект. Два источника, каждый со своим таймером, рано или поздно разъедутся,
    /// и игра останется замороженной навсегда.
    /// <para>
    /// Всё, что хочет заморозку, просит её здесь и не трогает <c>Time.timeScale</c>
    /// напрямую. Наложение запросов - забота реализации, а не вызывающего.
    /// </para>
    /// </summary>
    public interface IHitStopService
    {
        /// <summary>Заморозка идёт прямо сейчас</summary>
        bool IsFrozen { get; }

        /// <summary>
        /// Придержать время на <paramref name="seconds"/> нескалированных секунд,
        /// опустив масштаб до <paramref name="scale"/>.
        /// <para>
        /// Повторный вызов во время уже идущей заморозки не складывается с ней и не
        /// перезапускает её с нуля: он лишь продлевает её до более позднего из двух
        /// концов. Иначе серия попаданий одним взмахом останавливала бы игру
        /// на сумму всех своих заморозок.
        /// </para>
        /// </summary>
        /// <param name="seconds">Длительность в реальном времени. Ноль и меньше - ничего не делает</param>
        /// <param name="scale">Масштаб времени на время заморозки. 0 - полная остановка</param>
        void Freeze(float seconds, float scale);
    }
}
