using UnityEngine;

namespace CrateExpectations.Core.Events
{
    /// <summary>
    /// Кто-то позвал на помощь. Событие несёт только «откуда кричали» и «до кого
    /// докричались» - ни слова о том, кто кричит и кто должен прибежать: первое
    /// не нужно слушателю, второе решает он сам.
    /// <para>
    /// <b>Первый в проекте радиус-бродкаст, и в этом его смысл.</b> Все остальные
    /// радиусы здесь физические - спрашивающий сам щупает пространство
    /// (<c>OverlapSphere</c> у сенсора инспектора, у проверки земли, у свипа удара).
    /// Тут наоборот: <b>источник объявляет громкость, а каждый слушатель сам меряет,
    /// достал ли до него звук</b>. Так кричащему не нужно знать, кто вокруг, -
    /// а это ровно то, чего нельзя допускать между модулями.
    /// </para>
    /// <para>
    /// <b>Почему в <c>Core</c>, а не в модуле того, кто кричит.</b> Все доменные
    /// события проекта живут в своих модулях, и это первое исключение - вынужденное,
    /// а не стилистическое. Публикует событие сторона досмотра, слушает сторона
    /// стражи, а <c>Guards</c> и <c>Inspection</c> друг друга не видят: у них общая
    /// сборка ровно одна, и это <c>Core</c>. Ребро между модулями ради одного события
    /// стоило бы дороже.
    /// </para>
    /// </summary>
    public readonly struct AlertRaised
    {
        public AlertRaised(Vector3 position, float radius)
        {
            Position = position;
            Radius = radius;
        }

        /// <summary>Откуда кричали. Мировая точка, а не объект: кричащий подписчику не нужен</summary>
        public Vector3 Position { get; }

        /// <summary>
        /// На сколько метров вокруг слышно. Число едет в событии, а не лежит у слушателя,
        /// намеренно: громкость - свойство крика, и один и тот же крик обязан быть слышен
        /// всем одинаково далеко
        /// </summary>
        public float Radius { get; }
    }
}
