using UnityEngine;

namespace CrateExpectations.Core.Services
{
    /// <summary>
    /// Где сейчас игрок. Ровно столько, сколько нужно тем, кто на него реагирует, -
    /// и ни слова о том, из чего игрок состоит.
    /// <para>
    /// Контракт заведён здесь, а не в модуле игрока, по той же причине, что
    /// <see cref="IPlatformService"/> и <see cref="ISaveService"/>: <c>Guards</c>
    /// не ссылается на <c>Player</c> и ссылаться не должен - стражнику незачем знать
    /// про ввод, перенос груза и вьюмодель, а именно это он получил бы вместе
    /// с типом <c>PlayerController</c>. Модуль зависит от одного свойства, которое
    /// ему нужно, а не от всего игрока целиком.
    /// </para>
    /// <para>
    /// Поиском по сцене эту задачу решать нельзя, и в проекте она так нигде и не решена:
    /// <c>GameObject.Find</c>, <c>FindObjectOfType</c> и поиск по тегу в игровом коде
    /// не встречаются ни разу. Реализацию собирает <c>GameLifetimeScope</c> из того,
    /// что у него и так есть.
    /// </para>
    /// </summary>
    public interface IPlayerTarget
    {
        /// <summary>
        /// Есть ли на кого реагировать. Отдельным свойством, а не проверкой
        /// <see cref="Transform"/> на <c>null</c> у каждого вызывающего: у Unity-объектов
        /// сравнение с <c>null</c> перегружено, и полагаться на него в чужом коде -
        /// значит рассчитывать, что все помнят эту особенность
        /// </summary>
        bool Exists { get; }

        /// <summary>
        /// Где игрок. Отдельно от <see cref="Transform"/>, потому что подавляющему
        /// большинству нужна именно точка: погоне - куда идти, дистанции - от чего
        /// считать. Безопасно при отсутствии цели
        /// </summary>
        Vector3 Position { get; }

        /// <summary>
        /// Сам трансформ - тем, кому мало точки: развернуться на игрока, привязать
        /// эффект. Может быть <c>null</c>, если цели нет
        /// </summary>
        Transform Transform { get; }
    }
}
