using UnityEngine;

namespace CrateExpectations.Guards
{
    /// <summary>
    /// Геометрия восприятия: слышно ли и попадает ли в конус зрения. Чистая логика
    /// по образцу <see cref="GuardBrain"/> и <c>ClueEvaluator</c> - ни сцены,
    /// ни <c>MonoBehaviour</c>, ни физики, ни собственной случайности: одни и те же
    /// точки всегда дают один и тот же ответ, и потому это покрывается тестами
    /// без запуска сцены.
    /// <para>
    /// <b>Рейкаста здесь нет и не будет.</b> Проверка прямой видимости - физическая,
    /// её умеет только сцена, и она остаётся на стороне <see cref="GuardWitness"/>.
    /// Разделение не формальное: геометрия дешёвая и считается всегда, рейкаст дорогой
    /// и пускается только после того, как геометрия сказала «да».
    /// </para>
    /// <para>
    /// <b>Статический класс, в отличие от <see cref="GuardBrain"/></b>, и это не разнобой:
    /// у мозга есть смысл быть объектом (он принадлежит конкретному стражнику и однажды
    /// обзаведётся памятью), а здесь состояния нет вовсе - только арифметика над точками.
    /// </para>
    /// </summary>
    public static class PerceptionCheck
    {
        /// <summary>
        /// Слышно ли. Одна проверка дистанции - <b>стены сознательно игнорируются</b>:
        /// решение принято на старте проектирования системы, а не забыто по дороге.
        /// </summary>
        /// <param name="self">Где стоит слушающий</param>
        /// <param name="incident">Где случилось происшествие</param>
        /// <param name="radius">На сколько метров вокруг его слышно</param>
        public static bool CanHear(Vector3 self, Vector3 incident, float radius)
        {
            // Нулевой радиус - это «не слышит вовсе», а не «слышит ровно в точке»:
            // иначе выключенный слух срабатывал бы на драку под самым носом
            if (radius <= 0f)
                return false;

            return (incident - self).sqrMagnitude <= radius * radius;
        }

        /// <summary>
        /// Попадает ли происшествие в конус зрения: сначала дальность, потом угол.
        /// <para>
        /// Конус НАСТОЯЩИЙ, а не плоский сектор: и дистанция, и угол считаются
        /// в трёх измерениях. На ровной палубе разница невелика, но плоская проверка
        /// означала бы, что стражник одинаково видит и то, что у него под ногами,
        /// и то, что над головой.
        /// </para>
        /// </summary>
        /// <param name="eye">Точка глаз смотрящего - уже с поправкой на рост.
        /// Именно точка, а не трансформ: класс про геометрию, а не про сцену</param>
        /// <param name="forward">Куда смотрит. Нормализовать не обязательно</param>
        /// <param name="incident">Куда смотрим - точка происшествия</param>
        /// <param name="range">Дальность зрения, м</param>
        /// <param name="fovFullDegrees">ПОЛНАЯ ширина конуса, градусов (не половина)</param>
        public static bool CanSee(
            Vector3 eye, Vector3 forward, Vector3 incident, float range, float fovFullDegrees)
        {
            if (range <= 0f || fovFullDegrees <= 0f)
                return false;

            Vector3 toIncident = incident - eye;

            // Дальность - первой и по квадратам: корень здесь ничего не решает,
            // а отсекает эта проверка большинство случаев
            if (toIncident.sqrMagnitude > range * range)
                return false;

            // Ровно в точке глаз - видно. Угла в этом случае не существует,
            // и Vector3.Angle вернул бы ноль, но полагаться на это не стоит
            if (toIncident.sqrMagnitude <= Mathf.Epsilon)
                return true;

            return Vector3.Angle(forward, toIncident) <= fovFullDegrees * 0.5f;
        }
    }
}
