namespace CrateExpectations.Guards
{
    /// <summary>
    /// Чем стражник занят. Это НАМЕРЕНИЕ, а не состояние машины: решение о том,
    /// чего стражник хочет, принимает <see cref="GuardBrain"/>, а как именно это
    /// выглядит - состояние FSM, которое ему соответствует
    /// </summary>
    public enum GuardIntent
    {
        /// <summary>Стоять на посту и никуда не идти</summary>
        HoldPost,

        /// <summary>Обходить маршрут с остановками</summary>
        Patrol,

        /// <summary>
        /// Оправляться от удара: стоять на месте, пока играет вздрагивание.
        /// Добавлено в конец, а не по смыслу между соседями: порядок объявления -
        /// это данные, и вставка в середину переставила бы значения у остальных
        /// </summary>
        Stagger,

        /// <summary>Догонять игрока. Дописано в конец по той же причине, что <see cref="Stagger"/></summary>
        Chase,

        /// <summary>Бить. Дописано в конец по той же причине, что <see cref="Stagger"/></summary>
        Attack,
    }
}
