using UnityEngine;

namespace CrateExpectations.Guards
{
    /// <summary>
    /// Органы чувств стражника: как далеко он слышит драку и как далеко и широко её видит.
    /// Четвёртый ассет стражника, рядом с <see cref="GuardMovementDefinition"/>,
    /// <see cref="GuardReactionDefinition"/> и <see cref="GuardCombatDefinition"/>,
    /// и отдельный от них по той же причине, что они отдельны друг от друга:
    /// движение - это обход, реакция - ответ на чужой удар, боевой ассет - собственный
    /// удар, а этот - то, что стражник вообще замечает. Четыре разных повода править.
    /// <para>
    /// Все числа - плейсхолдеры, тюнятся без единой правки кода.
    /// </para>
    /// </summary>
    [CreateAssetMenu(
        fileName = "GuardPerceptionDefinition",
        menuName = "CrateExpectations/Guards/Guard Perception Definition")]
    public sealed class GuardPerceptionDefinition : ScriptableObject
    {
        // Слух намеренно ИГНОРИРУЕТ стены - решение принято на старте проектирования
        // системы, а не забыто. Порт - открытая палуба с парой перегородок, звук драки
        // за ящиками должен доноситься, и «честный» слух с трассировкой дал бы стражника,
        // который не слышит крика из-за угла в двух метрах от себя
        [Header("Слух")]
        [Tooltip("На каком расстоянии стражник слышит чужую драку, м. Сквозь стены: " +
                 "слух геометрию не проверяет вовсе, это одна проверка дистанции")]
        [field: SerializeField][Min(0f)] public float HearingRadius { get; private set; } = 6f;

        [Header("Зрение")]
        [Tooltip("Как далеко стражник видит, м. Дальше этого - не видит даже прямо перед собой")]
        [field: SerializeField][Min(0f)] public float VisionRange { get; private set; } = 10f;

        // ПОЛНЫЙ угол, не половинный, и это записано в самом имени поля намеренно:
        // перепутать их - классическая ошибка на ровном месте, и стоит она вдвое
        // (конус либо вчетверо уже, либо вчетверо шире задуманного). 100 полных
        // означает по 50 в каждую сторону от взгляда
        [Tooltip("ПОЛНАЯ ширина конуса зрения, градусов (не половина!). 100 означает " +
                 "по 50 влево и вправо от направления взгляда")]
        [field: SerializeField][Range(0f, 360f)] public float VisionFovFullDegrees { get; private set; } = 100f;

        // Число, а не ссылка на кость Head, и это решение фазы F, а не экономия.
        // Две причины, каждой достаточно по отдельности:
        //   1. голову вертит анимация (клип Looking на паузе патруля) - конус зрения
        //      ездил бы туда, куда её повернул художник;
        //   2. Animator.cullingMode = CullUpdateTransforms: вне кадра кости не пишутся
        //      вовсе. А свидетельство почти всегда происходит именно за кадром - игрок
        //      дерётся с одним стражником, второй смотрит со стороны.
        // Корень же ведёт NavMeshAgent, он жив всегда. Замер по префабу: кость Head
        // стоит на 1.446 м над корнем стражника
        [Tooltip("Высота глаз над корнем стражника, м. Числом, а не ссылкой на кость: " +
                 "кость Head вертится анимацией и замирает вне кадра (culling), " +
                 "а восприятие обязано работать за кадром. Замер по префабу - 1.45")]
        [field: SerializeField][Min(0f)] public float EyeHeight { get; private set; } = 1.45f;

        // Маска в ассете, а не константой в коде и не полем на компоненте, - по той же
        // причине, по которой в GuardCombatDefinition лежит маска удара: это число
        // геймплея. Только Ground: на нём в сцене лежат стены дока, пол и стол досмотра,
        // и больше ничего. Взять сюда Default означало бы, что стражники, ящики и бочки
        // перекрывают друг другу обзор, - для простой проверки «видит ли» это лишняя
        // точность, из-за которой свидетель молча слепнет за случайным ящиком
        [Tooltip("Что перекрывает обзор. Только Ground: стены дока. Слух эту маску " +
                 "НЕ смотрит вовсе - он сквозь стены по решению дизайна")]
        [field: SerializeField] public LayerMask SightBlockers { get; private set; }
    }
}
