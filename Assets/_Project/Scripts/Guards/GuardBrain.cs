namespace CrateExpectations.Guards
{
    /// <summary>
    /// Решает, чем стражнику заниматься. Чистая логика по образцу <c>ClueEvaluator</c>
    /// и <c>PayoutCalculator</c>: ни сцены, ни <c>MonoBehaviour</c>, ни собственной
    /// случайности - один и тот же контекст всегда даёт одно и то же намерение.
    /// <para>
    /// Правил сейчас ровно два, и отдельный класс под них выглядит избыточно -
    /// это осознанно. Мозг расширяется дальше (агрессия, тревога, преследование)
    /// <b>не меняя интерфейс</b>: новыми полями <see cref="GuardContext"/> и новыми
    /// ветками в <see cref="Decide"/>. Ни <c>GuardAI</c>, ни состояния FSM при этом
    /// не трогаются вовсе - они как спрашивали намерение, так и спрашивают.
    /// Заводить эту границу задним числом, когда правил станет шесть, дороже
    /// </para>
    /// </summary>
    public sealed class GuardBrain
    {
        /// <summary>Чем заняться при таких вводных</summary>
        /// <param name="context">Снимок того, что о стражнике известно</param>
        public GuardIntent Decide(in GuardContext context)
        {
            // Порядок веток здесь И ЕСТЬ приоритет намерений, и читается он сверху вниз.
            // Каждая следующая проверка означает «всё, что выше, уже не про нас»

            // Труп не делает ничего. В обычной жизни сюда не доходят - GuardDeath гасит
            // GuardAI целиком, - но здоровье смерть переживает, и если объект однажды
            // зажгут обратно, воскресать в погоню он не должен
            if (context.IsDead)
                return GuardIntent.HoldPost;

            // Удар бьёт всё остальное, включая начатую атаку: стражник, которого рубят,
            // не продолжает ни обход, ни собственный замах. Единственное исключение -
            // гипер-армор активной фазы, но он отсекается раньше, ЗА пределами мозга:
            // GuardHitReaction в такой момент просто не взводит вздрагивание
            if (context.IsStaggered)
                return GuardIntent.Stagger;

            // Начатый удар доигрывает - даже если игрок успел выйти из радиуса.
            // Без этой ветки стражник отменял бы собственный замах в тот же кадр,
            // когда игрок сделал шаг назад, и ударить не смог бы никогда:
            // сближение вернуло бы его в Attack, шаг назад снова отменил бы.
            // Проверка стоит ВЫШЕ радиуса именно поэтому
            if (context.IsAttackCommitted)
                return GuardIntent.Attack;

            if (context.IsAggro)
                return context.IsInAttackRange ? GuardIntent.Attack : GuardIntent.Chase;

            // Мирная жизнь - последней: до неё доходят только когда всё остальное молчит
            return context.HasPatrolRoute ? GuardIntent.Patrol : GuardIntent.HoldPost;
        }
    }
}
