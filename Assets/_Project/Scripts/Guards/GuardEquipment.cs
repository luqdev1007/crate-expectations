using CrateExpectations.Combat;
using UnityEngine;

namespace CrateExpectations.Guards
{
    /// <summary>
    /// Вешает оружие стражнику в руку на старте. Всё, что он делает, - один вызов
    /// <see cref="WeaponSocket.Mount"/>: посадка, масштаб и сам префаб клинка живут
    /// в ассете оружия, а не здесь.
    /// <para>
    /// Отдельный компонент, а не строчка в <see cref="GuardAI"/>, по той же причине,
    /// по которой у игрока этим занят не контроллер боя вообще: снять с префаба
    /// оружие должно быть удалением одного компонента, а не правкой поведения.
    /// </para>
    /// <para>
    /// Ножен у стражника нет, и убирать меч ему некуда - в отличие от игрока, который
    /// достаёт и прячет саблю по состоянию машины. Поэтому клинок просто показывается
    /// сразу и остаётся в руке; выбрасывать его при смерти будет отдельная фаза.
    /// </para>
    /// </summary>
    public sealed class GuardEquipment : MonoBehaviour
    {
        [Tooltip("Чем вооружён. Отсюда берутся префаб клинка и его посадка в ладони")]
        [SerializeField] private WeaponDefinition _weapon;

        [Tooltip("Пустышка под костью правой кисти, в которую вешается оружие")]
        [SerializeField] private WeaponSocket _socket;

        private void Awake()
        {
            if (_weapon == null || _socket == null)
            {
                Debug.LogError($"Стражнику '{name}' не назначено оружие или сокет - " +
                               "в руке будет пусто.", this);
                enabled = false;
                return;
            }

            _socket.Mount(_weapon);

            // Явно, а не полагаясь на то, что свежесозданный объект и так активен:
            // видимостью оружия у игрока распоряжается машина состояний, и читающий
            // этот код вправе ожидать, что решение принято здесь тоже
            _socket.SetVisible(true);
        }
    }
}
