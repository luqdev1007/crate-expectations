using UnityEngine;

namespace CrateExpectations.Guards
{
    /// <summary>
    /// Боевые числа стражника: с какого расстояния он бьёт, как быстро бежит и сколько
    /// длятся фазы удара. Один ассет на всех стражников - тот же приём, что
    /// у <see cref="GuardMovementDefinition"/> и <see cref="GuardReactionDefinition"/>.
    /// <para>
    /// Отдельный ассет от них обоих намеренно. <c>Movement</c> описывает обход, когда
    /// стражника никто не трогает; <c>Reaction</c> - как он отвечает на чужой удар;
    /// этот - как он бьёт сам. Три разных повода править и три разных дня, когда это
    /// делают.
    /// </para>
    /// </summary>
    [CreateAssetMenu(
        fileName = "GuardCombatDefinition",
        menuName = "CrateExpectations/Guards/Guard Combat Definition")]
    public sealed class GuardCombatDefinition : ScriptableObject
    {
        [Header("Дистанция")]
        [Tooltip("С какого расстояния до игрока стражник переходит от погони к удару, м. " +
                 "Сравнение простое, по дистанции между корнями, а не физический оверлап: " +
                 "оверлап отвечал бы на другой вопрос - «касаются ли объёмы», - а нужен " +
                 "именно порог «пора бить»")]
        [field: SerializeField][Min(0.5f)] public float AttackRange { get; private set; } = 2f;

        // Число обязано СОВПАДАТЬ с порогом бега в блендтри Move графа Guard.controller
        // (пороги: 0 idle / 1.17 шаг / 2.78 бег). GuardAnimatorDriver пишет в Speed
        // фактическую скорость агента в м/с без нормировки, поэтому скорость погони,
        // не дотягивающая до порога, даёт стражника, который едет с скоростью бега
        // в позе шага. Крутить только парой: сначала порог в блендтри, потом это поле.
        // Тот же урок, что со скоростью патруля 1.17 в фазе C
        [Header("Погоня")]
        [Tooltip("Скорость погони, м/с. ОБЯЗАНА совпадать с порогом бега в блендтри " +
                 "Move графа Guard.controller (сейчас 2.78). Правится только парой с ним: " +
                 "иначе стражник поедет со скоростью бега в анимации шага")]
        [field: SerializeField][Min(0f)] public float ChaseSpeed { get; private set; } = 2.78f;

        [Tooltip("Как часто в погоне пересчитывается путь до игрока, с. Не каждый кадр: " +
                 "SetDestination строит путь по навмешу, и звать его 60 раз в секунду " +
                 "ради цели, которая за кадр сдвинулась на сантиметры, - это работа впустую")]
        [field: SerializeField][Min(0f)] public float RepathInterval { get; private set; } = 0.2f;

        // Тайминги заданы ЧИСЛАМИ, а не выведены из длины клипа кодом, и это решение:
        // длину клипа правят художники, а темп боя - геймдизайнер, и связывать их
        // означало бы, что замена анимации молча меняет баланс. Сумма (1.8 с) с запасом
        // покрывает самый длинный клип атаки (Standing Melee Attack Downward, 1.767 с)
        // вместе с блендаутом в Locomotion, - иначе состояние успевало бы решить заново
        // и перезапустить замах на 60% проигрывания.
        //
        // Разбивка внутри суммы ЗАМЕРЕНА живьём (блок 8 фазы E), а не угадана. Для каждого
        // из трёх замахов снято, на каком куске клипа клинок физически накрывает игрока,
        // стоящего на границе радиуса (2 м):
        //     idx 0  Sword And Shield Slash            0.59 .. 1.16 с
        //     idx 1  Sword And Shield Slash (1)        0.28 .. 0.82 с
        //     idx 2  Standing Melee Attack Downward    0.62 .. 0.65 с   <- всего 2 кадра
        // Первая разбивка (0.25 / 0.35 / 1.2) открывала свип на 0.25..0.60 с и потому
        // РАЗМИНАЛАСЬ с третьим замахом полностью, а со вторым цеплялась последним кадром:
        // треть ударов не попадала никогда. Окно 0.55..0.95 пересекает все три
        [Header("Фазы удара, с")]
        [Tooltip("Замах: удар уже начался, но ещё не задевает. Столько у игрока есть " +
                 "на то, чтобы увидеть занесённый клинок")]
        [field: SerializeField][Min(0f)] public float AttackWindup { get; private set; } = 0.55f;

        [Tooltip("Активная фаза: только в ней свип ищет игрока. Она же - окно гипер-армора, " +
                 "в котором стражника нельзя сбить встречным ударом")]
        [field: SerializeField][Min(0f)] public float AttackActive { get; private set; } = 0.4f;

        [Tooltip("Доводка: удар уже не задевает, но стражник ещё занят. Здесь его снова " +
                 "можно прервать. Самая длинная фаза не случайно - именно она даёт клипу " +
                 "доиграть, а игроку окно на ответ")]
        [field: SerializeField][Min(0f)] public float AttackRecovery { get; private set; } = 0.85f;

        // Объём свипа задан числами здесь, а не снят с коллайдеров смонтированного клинка,
        // и это осознанно: коллайдеры на Ulfberht стоят под физику предмета, а не под
        // попадание по игроку, и подгонять баланс, двигая их, значило бы менять заодно
        // то, как меч лежит на палубе. Числа замерены по клинку и от него отвязаны:
        // Blade Collider длиной 1.10 при посадке 0.56 даёт 0.616 м, кончик - в 0.684 м
        // от кисти
        [Header("Объём удара")]
        [Tooltip("Длина рабочей части клинка от кисти, м. Свип идёт вдоль ЛОКАЛЬНОЙ ОСИ +Y " +
                 "смонтированного оружия - у Ulfberht клинок направлен именно туда, а не по +Z")]
        [field: SerializeField][Min(0.05f)] public float BladeLength { get; private set; } = 0.7f;

        [Tooltip("Радиус капсулы вокруг клинка, м. Не толщина меча, а щедрость попадания: " +
                 "слишком точный объём даёт удары, которые игрок считает прошедшими сквозь него")]
        [field: SerializeField][Range(0.05f, 1f)] public float SweepRadius { get; private set; } = 0.35f;

        [Header("Что делает удар")]
        [Tooltip("Урон за попадание. У игрока 100 HP, так что это ещё и число ударов до смерти")]
        [field: SerializeField][Min(0)] public int AttackDamage { get; private set; } = 10;

        [Tooltip("Импульс отбрасывания, Н·с. Игрока сейчас не двигает - его здоровье " +
                 "импульс игнорирует, как и ящик игнорирует урон, - но едет в HitInfo " +
                 "целиком, чтобы удар описывал себя одинаково для любой цели")]
        [field: SerializeField][Min(0f)] public float AttackImpulse { get; private set; } = 8f;

        [Tooltip("Сколько разных замахов лежит в графе Guard.controller под AttackIndex " +
                 "(сейчас три: 0, 1, 2). Число здесь, а не константой в коде: набор " +
                 "анимаций правят в графе, и код о том, сколько их, знать не должен")]
        [field: SerializeField][Min(1)] public int AttackVariants { get; private set; } = 3;

        [Header("Кого бьёт")]
        [Tooltip("Слои, по которым проходит свип удара. Только Player: маска из ассета " +
                 "оружия здесь не годится - у меча стражника она Everything, и он рубил бы " +
                 "палубу, ящики, соседних стражников и собственный труп")]
        [field: SerializeField] public LayerMask AttackMask { get; private set; }

        /// <summary>
        /// Сколько длится удар целиком, с. Считается, а не хранится отдельным полем:
        /// иначе четвёртое число разъехалось бы с суммой трёх при первой же правке
        /// </summary>
        public float AttackDuration => AttackWindup + AttackActive + AttackRecovery;
    }
}
