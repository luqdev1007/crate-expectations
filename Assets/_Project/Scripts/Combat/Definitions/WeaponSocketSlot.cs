namespace CrateExpectations.Combat
{
    /// <summary>
    /// Куда именно вешают оружие. Определяет, какой блок посадки из ассета читает сокет:
    /// у физического тела и у вьюмодели задачи разные и числа поэтому тоже разные
    /// </summary>
    public enum WeaponSocketSlot
    {
        /// <summary>
        /// Физическое тело в мире. Сабля должна лежать в ладони анатомически - её видно
        /// в тени на земле и по ней же будут читать позу игрока NPC
        /// </summary>
        Body = 0,

        /// <summary>
        /// Вьюмодель под камерой. Анатомия здесь никого не волнует: клинок ставят так,
        /// как он лучше лежит в кадре
        /// </summary>
        ViewModel = 1,
    }
}
