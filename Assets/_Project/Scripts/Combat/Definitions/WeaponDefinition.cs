using UnityEngine;

namespace CrateExpectations.Combat
{
    /// <summary>
    /// Всё про одно оружие: что вешать в руку, как оно там стоит и чем оно бьёт.
    /// <para>
    /// Чисел отдельного удара здесь нет и быть не должно: длительность, объём свипа,
    /// урон и импульс - свойства ПРИЁМА, а не сабли. Укол и рубящий отличаются всем,
    /// и один набор полей на оружие заставлял бы их быть одинаковыми. Приёмы лежат
    /// в <see cref="AttackSet"/>, здесь - только ссылка на раскладку.
    /// </para>
    /// </summary>
    [CreateAssetMenu(
        fileName = "WeaponDefinition",
        menuName = "CrateExpectations/Combat/Weapon Definition")]
    public sealed class WeaponDefinition : ScriptableObject
    {
        // Прямая ссылка, а не Addressables-ключ - осознанно, вопреки тому, как грузится груз.
        // Груз ходит через каталог потому, что его типов много, набор меняется от контракта
        // к контракту и держать всё в памяти незачем. Оружие противоположно по всем трём
        // пунктам: оно одно, нужно с первого кадра боя и живёт всю сессию. Асинхронная
        // загрузка тут не экономит память, зато добавляет кадр ожидания ровно в тот момент,
        // когда игрок нажал "достать". Плюс в бандл уходит копия ассета, и сравнение
        // ссылок на префаб перестаёт работать в билде - для оружия это лишний риск даром
        [Tooltip("Префаб оружия. Инстанцируется один раз при старте и просто прячется, " +
                 "пока оружие убрано")]
        [field: SerializeField] public GameObject Prefab { get; private set; }

        [Header("Приёмы")]
        [Tooltip("Раскладка: какое направление движения каким ударом отвечает. " +
                 "Отсюда же собирается граф аниматора вьюмодели")]
        [field: SerializeField] public AttackSet Attacks { get; private set; }

        // Посадок две, и они независимы намеренно. У физического тела задача анатомическая:
        // сабля должна выглядеть зажатой в кулаке, потому что её видно в тени на земле и
        // по ней же будут читать позу игрока NPC. У вьюмодели задачи анатомической нет вовсе -
        // её никто, кроме камеры, не видит, и клинок там ставят так, как он лучше лежит
        // в кадре. Одно поле на обе посадки означало бы, что подбор кадра ломает тень
        [Header("Посадка на физическом теле")]
        [Tooltip("Как сабля лежит в ладони мировой модели. Видна в тени, не в кадре")]
        [field: SerializeField] public WeaponFit BodySocket { get; private set; }

        [Header("Посадка на вьюмодели")]
        [Tooltip("Как сабля лежит в ладони модели под камерой. Видна в кадре, не в тени")]
        [field: SerializeField] public WeaponFit ViewModelSocket { get; private set; }

        // Клипы доставания и убирания лежат ЗДЕСЬ, а не в путях-константах генератора и не
        // в наборе небоевых поз. Причина простая: рядом уже лежат их длительности, и держать
        // «сколько длится» и «чем это показать» в разных ассетах значит гарантировать, что
        // однажды их поменяют по отдельности. Приём устроен так же - свой клип возит с собой
        [Header("Доставание и убирание")]
        [Tooltip("Клип доставания. Длину диктует не он, а DrawDuration: клип ужимается " +
                 "множителем скорости стейта")]
        [field: SerializeField] public AnimationClip DrawClip { get; private set; }

        [Tooltip("Клип убирания. Длину диктует SheatheDuration")]
        [field: SerializeField] public AnimationClip SheatheClip { get; private set; }

        [Header("Тайминги")]
        [Tooltip("Доставание, с")]
        [field: SerializeField][Min(0f)] public float DrawDuration { get; private set; } = 0.65f;

        [Tooltip("Убирание, с")]
        [field: SerializeField][Min(0f)] public float SheatheDuration { get; private set; } = 0.8f;

        // Доли, а не секунды: длительность фазы правится отдельно, и момент появления
        // клинка обязан ехать вместе с ней, а не отставать на пересчёт
        [Tooltip("На какой доле доставания клинок появляется в руке. Не середина: замер " +
                 "по клипу показал, что кисть уходит ЗА объектив на кадрах 40-52 из 98, " +
                 "и клинок, показанный раньше, дважды прошёл бы сквозь ближнюю плоскость. " +
                 "Вперёд рука окончательно выходит на 54% клипа")]
        [field: SerializeField][Range(0f, 1f)] public float DrawRevealFraction { get; private set; } = 0.54f;

        [Tooltip("На какой доле убирания клинок исчезает из руки. Замер: кисть уходит " +
                 "за объектив на 74% клипа и больше не возвращается - дальше клинка " +
                 "в кадре нет, и гасить его можно в любой момент после этого")]
        [field: SerializeField][Range(0f, 1f)] public float SheatheHideFraction { get; private set; } = 0.74f;

        [Header("Блок")]
        [Tooltip("Подъём клинка в блок, с. Держать равным длине клипа постановки, " +
                 "иначе поза оборвётся на середине")]
        [field: SerializeField][Min(0f)] public float BlockRaiseDuration { get; private set; } = 0.25f;

        [Tooltip("Опускание клинка из блока, с")]
        [field: SerializeField][Min(0f)] public float BlockLowerDuration { get; private set; } = 0.25f;

        [Header("Дуга взмаха")]
        [Tooltip("Чем машут вьюмоделью, когда включена процедурная дуга. Ассет отдельный: " +
                 "дуга - это числа кадра, а не оружия, и переживёт замену сабли на топор")]
        [field: SerializeField] public SwingDefinition Swing { get; private set; }

        // Поле отдельное от Swing, а не расширение его структуры, и это принципиально:
        // подготовка и взмах - разные движения, разведённые по времени и по механизму.
        // Взмах играется клипом (или кривыми, если включён тумблер), подготовка - только
        // слоем, и она идёт ДО удара, пока клипа нет вообще. Одно поле на оба означало бы,
        // что выключенная процедурная дуга выключает заодно и отвод заряда
        [Header("Подготовка заряда")]
        [Tooltip("Куда уводится вьюмодель, пока копится заряд. Ассет отдельный по той же " +
                 "причине, что и дуга: это числа кадра, а не оружия")]
        [field: SerializeField] public ChargeWindupDefinition ChargeWindup { get; private set; }

        // Свип идёт из камеры, а не по клинку вьюмодели, и это не упрощение. Вьюмодель
        // врёт про положение в мире: она висит под камерой, живёт в своём объективе и
        // подобрана под то, как красиво лежит в кадре, - её клинок физически находится
        // в паре десятков сантиметров от глаза, а не там, где его видит игрок. Детекция
        // обязана быть привязана к тому, КУДА ИГРОК ЦЕЛИТСЯ, иначе попадание расходится
        // с прицелом ровно на величину подгонки кадра
        [Header("Свип")]
        [Tooltip("По кому бьём. Общее на все приёмы: слои цели от удара к удару " +
                 "не меняются, меняется только объём - и он лежит у приёма")]
        [field: SerializeField] public LayerMask HitMask { get; private set; } = ~0;

        // Звуки лежат у оружия, а не в ассете фидбека: свист сабли и свист топора -
        // это разные звуки, а вот заморозка и тычок камеры у них общие
        [Header("Звук")]
        [Tooltip("Свист на старте взмаха. Играется с разбросом высоты тона")]
        [field: SerializeField] public AudioClip SwingSound { get; private set; }

        [Tooltip("Удар на контакте. Играется всегда одной высотой тона - " +
                 "он должен читаться как событие, а не как продолжение свиста")]
        [field: SerializeField] public AudioClip HitSound { get; private set; }

        [Header("Отдача кадра")]
        [Tooltip("Заморозка, тычок камеры и отдача вьюмодели. Ассет отдельный: " +
                 "это ощущение удара вообще, а не свойство конкретной сабли. " +
                 "Силу под себя каждый приём домножает своими множителями")]
        [field: SerializeField] public ImpactFeedbackDefinition Feedback { get; private set; }

        [Header("Задел")]
        [Tooltip("Длина клинка от сокета до острия, м. Дальность удара задаёт не она, " +
                 "а SweepDistance приёма: клинок вьюмодели в мире стоит не там, где выглядит")]
        [field: SerializeField][Min(0f)] public float BladeLength { get; private set; } = 0.76f;

        /// <summary>Тайминги в виде значения - то, с чем работает <see cref="WeaponStateMachine"/></summary>
        public WeaponTimings Timings =>
            new(DrawDuration, SheatheDuration, BlockRaiseDuration, BlockLowerDuration,
                DrawRevealFraction, SheatheHideFraction);
    }
}
