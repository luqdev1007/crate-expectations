namespace CrateExpectations.Combat
{
    /// <summary>
    /// Чем кончилось одно попадание по здоровью. Возвращается значением, а не читается
    /// потом со счётчика: между «нанесли урон» и «посмотрели, сколько осталось» может
    /// влезть второе попадание того же кадра, и тогда обработчик первого увидел бы
    /// чужое число
    /// </summary>
    public readonly struct DamageResult
    {
        public DamageResult(float newHp, bool died)
        {
            NewHp = newHp;
            Died = died;
        }

        /// <summary>Сколько здоровья осталось после удара. Ниже нуля не опускается</summary>
        public float NewHp { get; }

        /// <summary>
        /// Этот удар и был смертельным. Взводится РОВНО ОДИН раз за жизнь: удары
        /// по уже мёртвому не считаются вовсе - иначе два попадания одного взмаха
        /// дважды объявили бы о смерти
        /// </summary>
        public bool Died { get; }
    }
}
