namespace CrateExpectations.Combat
{
    /// <summary>
    /// Насколько тяжёлым удар ощущается ЦЕЛЬЮ. Не сила урона и не длительность приёма:
    /// это единственное, чем цель различает «задели» и «достали».
    /// <para>
    /// Заведён отдельным признаком, а не выведен из <c>Damage</c> или <c>HoldTime</c>
    /// на месте, и это не дублирование данных. Урон не годится: незаряженный
    /// <c>Attack_ThrustF_Light</c> и воздушная атака бьют на 2 наравне с заряженными.
    /// <c>HoldTime</c> не годится в общем случае: он про ВВОД (сколько держать кнопку),
    /// а тир про ОТДАЧУ, и у атаки в прыжке заряда нет физически - кнопку держать
    /// некогда, - хотя по весу это самый тяжёлый удар в ките. Признак, выводимый
    /// из двух других с исключениями, - это не признак, а правило, которое рано или
    /// поздно разойдётся с данными молча.
    /// </para>
    /// </summary>
    public enum AttackTier
    {
        /// <summary>
        /// Обычный удар. Цель его чувствует - хитстоп, искры, звук отрабатывают, -
        /// но с ног не сбивает: занятие цели не прерывается
        /// </summary>
        Light = 0,

        /// <summary>
        /// Тяжёлый удар. Прерывает то, чем цель занята, и заставляет отыграть реакцию
        /// </summary>
        Heavy = 1,
    }
}
