namespace CrateExpectations.Combat
{
    /// <summary>
    /// Куда игрок собирался двигаться в момент удара. Не «куда летит клинок» и не «куда
    /// едет тело»: это НАМЕРЕНИЕ, снятое с нажатых клавиш.
    /// <para>
    /// Скорость <c>Rigidbody</c> на эту роль не годится, и это проверяется первым же
    /// ударом: после отпускания клавиши в скорости ещё живёт инерция, при упоре в стену
    /// скорость нулевая, хотя игрок вовсю жмёт вперёд, а в прыжке к горизонтали
    /// подмешивается гравитация. Клавиши врать не умеют.
    /// </para>
    /// </summary>
    public enum AttackDirection
    {
        /// <summary>Стоя на месте</summary>
        Neutral = 0,

        /// <summary>Наступление</summary>
        Forward = 1,

        /// <summary>Отступление</summary>
        Backward = 2,

        /// <summary>Шаг вправо</summary>
        Right = 3,

        /// <summary>Шаг влево</summary>
        Left = 4,

        /// <summary>В воздухе. Бьёт по всему, что нажато: прыжок важнее направления</summary>
        Air = 5,
    }
}
