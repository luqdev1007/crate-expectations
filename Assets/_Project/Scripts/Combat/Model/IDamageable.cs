namespace CrateExpectations.Combat
{
    /// <summary>
    /// То, что умеет получать удар. Интерфейс, а не базовый класс: ящику нужно улететь,
    /// инспектору - возмутиться, бочке - развалиться, и общего состояния у них нет.
    /// <para>
    /// Ищется через <c>TryGetComponent</c> на задетом коллайдере, поэтому реализация
    /// обязана висеть либо на том же объекте, что коллайдер, либо выше по иерархии -
    /// см. <c>PhysicsHitReceiver</c>.
    /// </para>
    /// </summary>
    public interface IDamageable
    {
        /// <summary>
        /// Принять удар. Что с ним делать - дело реализации: урон, отбрасывание, звук,
        /// смена состояния или всё сразу
        /// </summary>
        void TakeHit(HitInfo hit);
    }
}
