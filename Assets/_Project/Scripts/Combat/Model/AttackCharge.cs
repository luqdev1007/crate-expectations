using UnityEngine;

namespace CrateExpectations.Combat
{
    /// <summary>
    /// Удержание кнопки удара: сколько её держат и дошло ли удержание до порога,
    /// на котором направление отдаёт свой заряженный приём.
    /// <para>
    /// Заряд заканчивается двумя способами, и оба - это удар. Игрок либо отпустил
    /// кнопку раньше порога и получил незаряженный вариант, либо додержал - и тогда
    /// удар уходит САМ, не дожидаясь отпускания. Второе принципиально: ждать
    /// отпускания там, где заряд уже полный, значит заставлять игрока отпускать
    /// кнопку ради того, что он уже заслужил, - и порог перестаёт чувствоваться,
    /// потому что в момент его прохождения не происходит ничего.
    /// </para>
    /// <para>
    /// Обычный C#-класс без времени Unity внутри, как <see cref="AttackInputBuffer"/>:
    /// время приходит аргументом <see cref="Tick"/>, и проверить срабатывание порога
    /// можно тестом, а не секундомером в play mode.
    /// </para>
    /// </summary>
    public sealed class AttackCharge
    {
        private float _threshold;

        /// <summary>Держит ли игрок кнопку прямо сейчас, копя заряд</summary>
        public bool IsCharging { get; private set; }

        /// <summary>Сколько удержание уже длится, с</summary>
        public float Held { get; private set; }

        /// <summary>
        /// Кнопку нажали. Порог приходит снаружи, потому что он свойство НАПРАВЛЕНИЯ:
        /// удар вперёд заряжается, удар стоя нет, и знать об этом должна раскладка,
        /// а не счётчик времени
        /// </summary>
        /// <param name="threshold">Сколько держать до полного заряда, с</param>
        public void Begin(float threshold)
        {
            _threshold = Mathf.Max(0f, threshold);
            Held = 0f;
            IsCharging = true;
        }

        /// <summary>
        /// Копит удержание. Возвращает <c>true</c> ровно один раз - в тот момент, когда
        /// заряд дошёл до порога. Один раз, а не каждый кадр после: это команда «бей»,
        /// и повторять её значило бы бить каждый кадр, пока кнопка зажата
        /// </summary>
        public bool Tick(float deltaTime)
        {
            if (!IsCharging)
                return false;

            Held += deltaTime;

            if (Held < _threshold)
                return false;

            IsCharging = false;

            return true;
        }

        /// <summary>
        /// Кнопку отпустили. Отдаёт накопленное удержание и гасит заряд.
        /// Ноль здесь означает, что заряда не было вовсе, - например, кнопку отпустили
        /// уже после того, как полный заряд ушёл в удар сам
        /// </summary>
        public float Release()
        {
            if (!IsCharging)
                return 0f;

            IsCharging = false;

            return Held;
        }

        /// <summary>
        /// Забыть удержание без удара. Нужно там, где сама возможность бить пропала -
        /// например, оружие убрали посреди заряда: отпущенная потом кнопка не должна
        /// выстрелить ударом
        /// </summary>
        public void Clear()
        {
            IsCharging = false;
            Held = 0f;
        }
    }
}
