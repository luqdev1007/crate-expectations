namespace CrateExpectations.Economy
{
    /// <summary>
    /// Кошелёк игрока. Единственный способ изменить баланс - применить готовый расчёт:
    /// "прибавь сто" снаружи сказать нельзя, и потому в игре нет ни одного начисления
    /// без причины, которую можно показать
    /// </summary>
    public interface IEconomyService
    {
        /// <summary>Сколько денег сейчас. Может быть отрицательным - долг разрешён</summary>
        int Balance { get; }

        /// <summary>Долг перевалил за допустимый предел</summary>
        bool IsBankrupt { get; }

        /// <summary>
        /// Применить расчёт к балансу и объявить об этом в шину. Нулевой расчёт
        /// ничего не меняет и события не порождает
        /// </summary>
        void Apply(in PayoutResult payout);

        /// <summary>
        /// Снять состояние для сохранения. Кошелёк отдаёт своё состояние сам - координатор
        /// сохранения в его внутренности не лезет и про баланс ничего не решает
        /// </summary>
        EconomySnapshot Capture();

        /// <summary>
        /// Вернуть состояние из сохранения. Это не начисление: разбивки нет, объяснять
        /// игроку нечего, - поэтому событие изменения баланса не публикуется
        /// </summary>
        void Restore(in EconomySnapshot snapshot);
    }
}
